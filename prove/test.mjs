import assert from "node:assert/strict";
import { protetto, tipoAttrezzo, livelloRichiesto, contaOggetti, togli } from "./scripts/azioni.js";
import { RICETTE, GRUPPI, assiDaTronco } from "./scripts/ricette.js";
import { proteggi } from "./scripts/memoria.js";
const bot = { dimension: { id: "minecraft:overworld" } };
const b = (typeId, x = 0) => ({ typeId: `minecraft:${typeId}`, location: { x, y: 64, z: 0 } });
for (const t of ["grass_block", "dirt", "stone", "deepslate", "oak_log", "iron_ore", "deepslate_diamond_ore", "sand", "gravel", "snow_block", "cobblestone"]) assert.equal(protetto(bot, b(t)), false, t);
for (const t of ["oak_planks", "glass", "chest", "crafting_table", "stone_bricks", "white_wool", "bedrock", "oak_door", "iron_block", "cobblestone_wall", "torch"]) assert.equal(protetto(bot, b(t)), true, t);
proteggi(bot.dimension, { x: 5, y: 64, z: 0 });
assert.equal(protetto(bot, b("cobblestone", 5)), true);
assert.equal(tipoAttrezzo("minecraft:oak_log"), "axe");
assert.equal(tipoAttrezzo("minecraft:grass_block"), "shovel");
assert.equal(tipoAttrezzo("minecraft:deepslate_iron_ore"), "pickaxe");
assert.equal(livelloRichiesto("minecraft:deepslate_diamond_ore"), 3);
assert.equal(livelloRichiesto("minecraft:iron_ore"), 2);
assert.equal(livelloRichiesto("minecraft:stone"), 1);
assert.equal(livelloRichiesto("minecraft:nether_gold_ore"), 1);
assert.equal(livelloRichiesto("minecraft:oak_log"), 0);
assert.equal(assiDaTronco("minecraft:stripped_dark_oak_log"), "minecraft:dark_oak_planks");
assert.equal(assiDaTronco("minecraft:crimson_stem"), "minecraft:crimson_planks");
assert.ok(GRUPPI["#tronco"]("minecraft:birch_log") && !GRUPPI["#tronco"]("minecraft:birch_planks"));
assert.deepEqual(RICETTE["minecraft:stone_pickaxe"].ing, { "#pietra": 3, "minecraft:stick": 2 });
const slots = [{ typeId: "minecraft:oak_log", amount: 3 }, null, { typeId: "minecraft:birch_log", amount: 2 }];
const finto = { getComponent: () => ({ container: { size: 3, getItem: (i) => slots[i] ?? undefined, setItem: (i, v) => { slots[i] = v ?? null; } } }) };
assert.equal(contaOggetti(finto, "#tronco"), 5);
assert.deepEqual(togli(finto, "#tronco", 4), ["minecraft:oak_log", "minecraft:oak_log", "minecraft:oak_log", "minecraft:birch_log"]);
assert.equal(contaOggetti(finto, "#tronco"), 1);
console.log("test JS ok");
